import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { getDb } from './db.ts';
import { logAudit } from './auditService.ts';

/**
 * PHASE 10.0 — Company identity, bilingual profile and logo storage.
 *
 * Single source of truth for company identity: the UI settings screen, the
 * application shell and every printable report read through this service, so a
 * change here propagates everywhere with no duplicated header markup.
 *
 * Storage decision: the logo is written to a dedicated directory on disk
 * (`uploads/company`) and the database keeps ONLY the stored file name.
 * Rationale:
 *   * PGlite in this project runs in-memory, so a blob in the database would be
 *     lost on restart — it is not a durable store for binaries here.
 *   * A client-supplied path or a data: URL would either break across machines
 *     or bloat every row. Neither is accepted.
 *   * The public URL is always the generated /api/company/logo/:file route, so
 *     no filesystem path is ever exposed through the API.
 */

export interface CompanyProfile {
  id: string;
  // Arabic (authoritative side: the pre-existing columns)
  nameAr: string;
  legalNameAr: string | null;
  addressAr: string | null;
  phone: string | null;
  email: string | null;
  taxNumber: string | null;
  // English
  nameEn: string | null;
  legalNameEn: string | null;
  addressEn: string | null;
  phoneEn: string | null;
  emailEn: string | null;
  // Shared
  website: string | null;
  commercialRegistration: string | null;
  logoFileName: string | null;
  logoUrl: string | null;
}

export const COMPANY_LOGO_DIR = path.resolve(process.cwd(), 'uploads', 'company');
export const MAX_LOGO_BYTES = 2 * 1024 * 1024; // 2 MB

/**
 * Allowed image formats. SVG is deliberately EXCLUDED: an SVG is an executable
 * XML document that can carry <script>, external references and CSS payloads.
 * Verifying it safely would require a real sanitizer, which the project has no
 * dependency for — so it is rejected rather than half-supported.
 */
const ALLOWED_IMAGE_TYPES: Record<string, { ext: string; mime: string }> = {
  png: { ext: 'png', mime: 'image/png' },
  jpeg: { ext: 'jpg', mime: 'image/jpeg' },
  webp: { ext: 'webp', mime: 'image/webp' },
};

/** Stored file names are generated by us and must look exactly like this. */
const STORED_NAME_RE = /^[a-f0-9]{32}\.(png|jpg|webp)$/;

/**
 * Detects the real image type from the file BYTES.
 *
 * A client-declared Content-Type / filename extension is attacker-controlled,
 * so it is only ever used as a hint and never as the decision. This is the
 * check that actually blocks a renamed `.exe` or an HTML/JS payload.
 */
export function sniffImageType(buffer: Buffer): string | null {
  if (!buffer || buffer.length < 12) return null;

  // PNG: 89 50 4E 47 0D 0A 1A 0A  ("\x89PNG\r\n\x1a\n")
  if (
    buffer[0] === 0x89 && buffer[1] === 0x50 && buffer[2] === 0x4e && buffer[3] === 0x47 &&
    buffer[4] === 0x0d && buffer[5] === 0x0a && buffer[6] === 0x1a && buffer[7] === 0x0a
  ) {
    return 'png';
  }

  // JPEG: FF D8 FF ... then a real APPn/SOFn marker before any payload.
  if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    const isTruncatedJpeg = buffer.length > 3 && buffer[3] === 0xff;
    if (!isTruncatedJpeg) return 'jpeg';
  }

  // WebP: "RIFF" <4-byte size> "WEBP"
  if (
    buffer.slice(0, 4).toString('ascii') === 'RIFF' &&
    buffer.slice(8, 12).toString('ascii') === 'WEBP'
  ) {
    return 'webp';
  }

  return null;
}

function toPublicProfile(row: any): CompanyProfile {
  return {
    id: row.id,
    nameAr: row.name,
    legalNameAr: row.legal_name ?? null,
    addressAr: row.address ?? null,
    phone: row.phone ?? null,
    email: row.email ?? null,
    taxNumber: row.tax_number ?? null,
    nameEn: row.name_en ?? null,
    legalNameEn: row.legal_name_en ?? null,
    addressEn: row.address_en ?? null,
    phoneEn: row.phone_en ?? null,
    emailEn: row.email_en ?? null,
    website: row.website ?? null,
    commercialRegistration: row.commercial_registration ?? null,
    logoFileName: row.logo ?? null,
    logoUrl: row.logo ? `/api/company/logo/${row.logo}` : null,
  };
}

export class CompanyService {
  /** Reads the (single) company row and maps it to the public profile shape. */
  static async getProfile(): Promise<CompanyProfile> {
    const db = await getDb();
    const res = await db.query<any>('SELECT * FROM core.companies ORDER BY created_at ASC LIMIT 1');
    if (res.rows.length === 0) {
      throw new Error('لا توجد بيانات شركة في النظام');
    }
    return toPublicProfile(res.rows[0]);
  }

  static async companyId(): Promise<string> {
    const db = await getDb();
    const res = await db.query<any>('SELECT id FROM core.companies ORDER BY created_at ASC LIMIT 1');
    if (res.rows.length === 0) throw new Error('لا توجد بيانات شركة في النظام');
    return res.rows[0].id;
  }

  /**
   * Updates the bilingual profile as a PARTIAL update.
   *
   * PHASE 10.0.1 — only keys actually PRESENT in the payload are written.
   * Previously every field was rewritten on every save (absent keys became
   * NULL), so saving one field silently wiped the rest of the profile. A field
   * is cleared only when the caller sends it EXPLICITLY as null or '' — which
   * is what the settings form's clear button does.
   *
   * `logo` is never part of this payload: the logo has its own endpoints, so a
   * profile save can never silently drop or overwrite a stored logo.
   */
  static async updateProfile(
    input: {
      nameAr?: string;
      legalNameAr?: string | null;
      addressAr?: string | null;
      phone?: string | null;
      email?: string | null;
      taxNumber?: string | null;
      nameEn?: string | null;
      legalNameEn?: string | null;
      addressEn?: string | null;
      phoneEn?: string | null;
      emailEn?: string | null;
      website?: string | null;
      commercialRegistration?: string | null;
    },
    userId?: string
  ): Promise<CompanyProfile> {
    const db = await getDb();
    const id = await this.companyId();

    const current = await this.getProfile();
    const has = (k: keyof typeof input) => Object.prototype.hasOwnProperty.call(input, k) && input[k] !== undefined;

    // The Arabic name is the only mandatory side — without it the header has
    // no identity at all, and every existing query assumes it is present.
    const rawNameAr = has('nameAr') ? input.nameAr : current.nameAr;
    const nameAr = (rawNameAr ?? '').trim();
    if (!nameAr) {
      throw new Error('اسم الشركة بالعربية مطلوب');
    }
    if (nameAr.length > 255) {
      throw new Error('اسم الشركة بالعربية يتجاوز الحد المسموح (255 حرفًا)');
    }

    const pick = <K extends keyof typeof input>(key: K, currentValue: any): string | null => {
      if (!has(key)) return currentValue === null || currentValue === undefined ? null : String(currentValue);
      const v = input[key];
      if (v === null) return null;
      const s = String(v).trim();
      return s.length === 0 ? null : s;
    };

    // Validate the optional English name against the same DB-level guard so the
    // service and the database never disagree about what is storable.
    const nameEn = has('nameEn')
      ? pick('nameEn', current.nameEn)
      : (current.nameEn ? String(current.nameEn).trim().slice(0, 255) || null : null);
    const commercialRegistration = pick('commercialRegistration', current.commercialRegistration)
      ?.slice(0, 100) ?? null;

    const email = pick('email', current.email);
    if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) {
      throw new Error('البريد الإلكتروني غير صالح');
    }
    const emailEn = pick('emailEn', current.emailEn);
    if (emailEn && !/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(emailEn)) {
      throw new Error('البريد الإلكتروني بالإنجليزية غير صالح');
    }
    const website = pick('website', current.website);
    if (website && !/^(https?:\/\/)?[\w.-]+\.[a-z]{2,}(\/\S*)?$/i.test(website)) {
      throw new Error('الموقع الإلكتروني غير صالح');
    }

    await db.query(
      `UPDATE core.companies SET
         name = $1, legal_name = $2, address = $3, phone = $4, email = $5, tax_number = $6,
         name_en = $7, legal_name_en = $8, address_en = $9, phone_en = $10, email_en = $11,
         website = $12, commercial_registration = $13, updated_at = NOW()
       WHERE id = $14`,
      [
        nameAr,
        pick('legalNameAr', current.legalNameAr),
        pick('addressAr', current.addressAr),
        pick('phone', current.phone),
        email,
        pick('taxNumber', current.taxNumber),
        nameEn,
        pick('legalNameEn', current.legalNameEn),
        pick('addressEn', current.addressEn),
        pick('phoneEn', current.phoneEn),
        emailEn,
        website,
        commercialRegistration,
        id,
      ]
    );

    await logAudit({
      userId,
      action: 'UPDATE',
      entityType: 'COMPANY',
      entityId: id,
      newData: { nameAr, nameEn },
    });

    return this.getProfile();
  }

  /**
   * Stores an uploaded logo.
   *
   * Order of checks matters: size first (cheap), then BYTES (authoritative),
   * then the client hint (never trusted). The stored name is a random digest —
   * the client never influences the filename, so traversal, double extensions
   * and overwriting are all impossible by construction.
   */
  static async saveLogo(base64: string, userId?: string): Promise<CompanyProfile> {
    const db = await getDb();
    const id = await this.companyId();

    if (!base64 || typeof base64 !== 'string') {
      throw new Error('لم يتم استلام أي ملف');
    }
    // Accept a bare base64 payload or a data: URL, but only by stripping a
    // prefix we recognise — the bytes are validated regardless.
    const commaIdx = base64.indexOf(',');
    const payload = base64.startsWith('data:') && commaIdx > -1 ? base64.slice(commaIdx + 1) : base64;

    let buffer: Buffer;
    try {
      buffer = Buffer.from(payload, 'base64');
    } catch {
      throw new Error('تعذر قراءة محتوى الملف المرفوع');
    }
    if (buffer.length === 0) {
      throw new Error('الملف المرفوع فارغ');
    }
    if (buffer.length > MAX_LOGO_BYTES) {
      throw new Error('حجم الشعار يتجاوز الحد المسموح (2 ميجابايت)');
    }

    // THE authoritative check — content, not extension.
    const sniffed = sniffImageType(buffer);
    if (!sniffed || !ALLOWED_IMAGE_TYPES[sniffed]) {
      throw new Error(
        'صيغة الملف غير مدعومة أو غير آمنة. المسموح فقط: PNG أو JPEG أو WebP (SVG غير مقبول لأسباب أمنية)'
      );
    }

    const fileName = `${crypto.randomBytes(16).toString('hex')}.${ALLOWED_IMAGE_TYPES[sniffed].ext}`;
    fs.mkdirSync(COMPANY_LOGO_DIR, { recursive: true });
    fs.writeFileSync(path.join(COMPANY_LOGO_DIR, fileName), buffer);

    // Replace the pointer, then delete the superseded file so the directory
    // never accumulates orphans and never serves a stale logo.
    const previous = await db.query<any>('SELECT logo FROM core.companies WHERE id = $1', [id]);
    const previousName = previous.rows[0]?.logo ?? null;

    await db.query('UPDATE core.companies SET logo = $1, updated_at = NOW() WHERE id = $2', [fileName, id]);
    if (previousName && previousName !== fileName) {
      this.safeDelete(previousName);
    }

    await logAudit({
      userId,
      action: 'UPLOAD',
      entityType: 'COMPANY_LOGO',
      entityId: id,
      newData: { fileName, bytes: buffer.length, mime: ALLOWED_IMAGE_TYPES[sniffed].mime },
    });

    return this.getProfile();
  }

  /** Removes the logo and deletes the stored file. Never touches other data. */
  static async removeLogo(userId?: string): Promise<CompanyProfile> {
    const db = await getDb();
    const id = await this.companyId();

    const res = await db.query<any>('SELECT logo FROM core.companies WHERE id = $1', [id]);
    const current = res.rows[0]?.logo ?? null;

    await db.query('UPDATE core.companies SET logo = NULL, updated_at = NOW() WHERE id = $1', [id]);
    if (current) this.safeDelete(current);

    await logAudit({
      userId,
      action: 'DELETE',
      entityType: 'COMPANY_LOGO',
      entityId: id,
      oldData: { fileName: current },
    });

    return this.getProfile();
  }

  /**
   * Resolves a public logo name to an ABSOLUTE path, or null.
   *
   * Guards, in order: strict whitelist regex (no separators, no dots beyond the
   * extension), then path.resolve containment inside COMPANY_LOGO_DIR, then an
   * existence check. Any failure yields null rather than a filesystem error,
   * so no internal path information ever escapes through the API.
   */
  static resolveLogoFile(fileName: string): string | null {
    if (!fileName || !STORED_NAME_RE.test(fileName)) return null;
    const full = path.resolve(COMPANY_LOGO_DIR, fileName);
    const root = path.resolve(COMPANY_LOGO_DIR);
    if (full !== root && !full.startsWith(root + path.sep)) return null;
    if (!fs.existsSync(full) || !fs.statSync(full).isFile()) return null;
    return full;
  }

  static mimeFor(fileName: string): string {
    const ext = path.extname(fileName).toLowerCase();
    if (ext === '.png') return 'image/png';
    if (ext === '.webp') return 'image/webp';
    if (ext === '.jpg' || ext === '.jpeg') return 'image/jpeg';
    return 'application/octet-stream';
  }

  private static safeDelete(fileName: string) {
    try {
      const full = this.resolveLogoFile(fileName);
      if (full) fs.unlinkSync(full);
    } catch {
      // A leftover file must never fail the request that removed the pointer.
    }
  }
}